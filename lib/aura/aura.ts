export type AuraScores = Record<ScoreId, number>;

/** 回答（各問で選んだ選択肢のindex配列：A=0/B=1/C=2/D=3）からスコアを集計する。 */
export function tallyAuraScores(answers: number[]): AuraScores {
  const scores = Object.fromEntries(scoreColors.map((id) => [id, 0])) as AuraScores;

  answers.forEach((optionIndex, questionIndex) => {
    const option = auraQuestions[questionIndex]?.options[optionIndex];
    if (!option) return;
    for (const [colorId, point] of Object.entries(option.scores)) {
      scores[colorId as ScoreId] += point ?? 0;
    }
  });

  return scores;
}

/**
 * 回答からオーラカラーのIDを算出する。
 *
 * 判定順：
 * 1. 虹（rainbow）を最優先：上位1位と2位の点差が1点以内 かつ 上位3色すべてが6点以上。
 * 2. 黒（black）：purple≥5 かつ silver≥5 かつ blue≥2。
 * 3. 上記以外：最高スコアの色（同点時は優先順位で判定）。
 *
 * ※ black・rainbow はシークレット判定のみで出現する。
 */
export function computeAuraId(answers: number[]): AuraId {
  const scores = tallyAuraScores(answers);

  // 通常11色をランキング（black / rainbow は除外）。同点時は優先順位。
  const ranked = tieBreakOrder.slice().sort((a, b) => {
    if (scores[b] !== scores[a]) return scores[b] - scores[a];
    return tieBreakOrder.indexOf(a) - tieBreakOrder.indexOf(b);
  });

  const [first, second, third] = ranked;

  // 1. 虹のオーラ判定（最優先）
  const rainbowCond =
    scores[first] - scores[second] <= 1 &&
    scores[first] >= 6 &&
    scores[second] >= 6 &&
    scores[third] >= 6;
  if (rainbowCond) return "rainbow";

  // 2. 黒のオーラ判定（虹の次）
  const blackCond = scores.purple >= 5 && scores.silver >= 5 && scores.blue >= 2;
  if (blackCond) return "black";

  // 3. 最高スコアの色
  return first;
}

/** 回答からオーラカラーを算出する。 */
export function computeAuraResult(answers: number[]): AuraColor {
  return auraColors[computeAuraId(answers)];
}

/** type クエリなどの文字列が有効なオーラIDか判定する。 */
export function isAuraId(value: string | null | undefined): value is AuraId {
  return value != null && value in auraColors;
}
