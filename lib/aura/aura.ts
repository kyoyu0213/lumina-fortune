// オーラカラー診断のデータとロジック。
// 10問・4択 → 各選択肢に設定された色へ加点 → 最高得点の色を結果に。
// 通常12色＋シークレット2色（black / rainbow）。
// 鑑定文・結果イラストは後で追加する前提（image は任意）。

export type AuraId =
  | "red"
  | "orange"
  | "yellow"
  | "green"
  | "lightblue"
  | "blue"
  | "purple"
  | "pink"
  | "white"
  | "silver"
  | "black"
  | "gold"
  | "rainbow";

// 質問で加点される色（rainbow を除く12色）。black は通常質問では直接加点しない。
export type ScoreId = Exclude<AuraId, "rainbow">;

/** 結果ページの鑑定文（セクションごと）。改行は \n で表現する。 */
export type AuraReading = {
  /** 概要 */
  overview: string;
  /** 性格 */
  personality: string;
  /** 恋愛傾向 */
  love: string;
  /** 才能と適職 */
  work: string;
  /** ルミナからの手紙 */
  letter: string;
};

export type AuraColor = {
  id: AuraId;
  /** 結果名（例：赤のオーラ） */
  name: string;
  /** テーマ（例：情熱・行動力・挑戦） */
  theme: string;
  /**
   * 結果イラスト（/public からの絶対パス）。
   * 画像を用意したら image: "/gazou/aura/red.png" のように設定してください。
   * 未設定でも結果ページは崩れません（プレースホルダー枠を表示）。
   */
  image?: string;
  /**
   * 鑑定文。未設定の色は結果ページで「この鑑定文は後ほど追加します。」を表示する。
   */
  reading?: AuraReading;
  /** シークレットタイプか */
  secret?: boolean;
};

