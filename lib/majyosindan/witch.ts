/** 相性の良い魔女（メダル付き） */
export type WitchCompatibility = {
  medal: string; // 🥇 / 🥈 / 🥉 など
  name: string; // 例: 月の魔女
  mbti: string; // 例: INFJ
  text: string;
};

/** 少し刺激的な相手 */
export type WitchRival = {
  emoji: string; // 例: 🖤
  name: string;
  mbti: string;
  text: string;
};

