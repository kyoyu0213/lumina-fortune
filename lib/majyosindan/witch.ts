/**
 * 回答（各質問で選んだ選択肢の pole）から MBTI タイプを算出する。
 * 各軸3問ずつなので引き分けは発生しない。
 */
export function computeMBTI(answers: Pole[]): MBTIType {
  const count: Record<Pole, number> = {
    E: 0, I: 0, S: 0, N: 0, T: 0, F: 0, J: 0, P: 0,
  };
  for (const pole of answers) {
    count[pole] += 1;
  }

  const ei: AxisEI = count.E >= count.I ? "E" : "I";
  const sn: AxisSN = count.S >= count.N ? "S" : "N";
  const tf: AxisTF = count.T >= count.F ? "T" : "F";
  const jp: AxisJP = count.J >= count.P ? "J" : "P";

  return `${ei}${sn}${tf}${jp}` as MBTIType;
}

export function getWitchResult(mbti: MBTIType): WitchResult {
  return witchResults[mbti];
}
